CREATE TABLE identification_heatmaps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identification_id BIGINT NOT NULL,
    identification_image_id BIGINT NOT NULL,
    storage_key TEXT,
    source_url TEXT,
    content_type VARCHAR(100),
    sequence_number INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT fk_identification_heatmaps_identification
        FOREIGN KEY (identification_id)
            REFERENCES identifications(id)
            ON DELETE CASCADE,

    CONSTRAINT fk_identification_heatmaps_image
        FOREIGN KEY (identification_image_id)
            REFERENCES identification_images(id)
            ON DELETE CASCADE,

    CONSTRAINT chk_identification_heatmaps_sequence
        CHECK (sequence_number > 0),

    CONSTRAINT chk_identification_heatmaps_reference
        CHECK (storage_key IS NOT NULL OR source_url IS NOT NULL)
);

CREATE INDEX idx_identification_heatmaps_identification
    ON identification_heatmaps(identification_id);

CREATE INDEX idx_identification_heatmaps_image
    ON identification_heatmaps(identification_image_id);

CREATE TRIGGER update_identification_heatmaps_updated_at
BEFORE UPDATE ON identification_heatmaps
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
