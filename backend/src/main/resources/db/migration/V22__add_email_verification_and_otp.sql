-- Email verification, OTP storage and JWT revocation.
--
-- Existing accounts were created before email verification existed, so they keep access:
-- the backfill below marks them verified. Only accounts created after this migration must
-- prove ownership of their address before they can log in.

ALTER TABLE users
    ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN email_verified_at TIMESTAMPTZ,
    ADD COLUMN token_version INTEGER NOT NULL DEFAULT 0;

UPDATE users
SET email_verified = TRUE,
    email_verified_at = CURRENT_TIMESTAMP
WHERE email_verified = FALSE;

-- One hashed OTP per user and purpose. Plaintext codes are never stored.
CREATE TABLE email_otps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    purpose VARCHAR(32) NOT NULL,
    otp_hash VARCHAR(64) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    last_sent_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_email_otps_purpose
        CHECK (purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET')),
    CONSTRAINT chk_email_otps_attempts
        CHECK (attempts >= 0)
);

-- At most one unused OTP per (user, purpose): two codes can never be valid at once.
CREATE UNIQUE INDEX uq_email_otps_active
    ON email_otps (user_id, purpose)
    WHERE consumed_at IS NULL;

CREATE INDEX idx_email_otps_expires_at ON email_otps (expires_at);

-- JWT ids that were explicitly logged out before their natural expiry.
CREATE TABLE revoked_tokens (
    jti UUID PRIMARY KEY,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_revoked_tokens_expires_at ON revoked_tokens (expires_at);
