-- Pending registration storage for OTP-before-account-creation flow.
-- Stores email, password hash, and OTP until verification completes.

CREATE TABLE pending_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL DEFAULT 'USER',
    otp_hash VARCHAR(64) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    last_sent_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_pending_registrations_email UNIQUE (email)
);

CREATE INDEX idx_pending_registrations_expires_at ON pending_registrations (expires_at);
CREATE INDEX idx_pending_registrations_email ON pending_registrations (email);

-- Extend OTP purpose enum to support pending registration verification.
-- Note: The email_otps table uses a CHECK constraint on purpose.
-- We add PENDING_REGISTRATION to the allowed values.
ALTER TABLE email_otps
    DROP CONSTRAINT chk_email_otps_purpose,
    ADD CONSTRAINT chk_email_otps_purpose
        CHECK (purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET', 'PENDING_REGISTRATION'));