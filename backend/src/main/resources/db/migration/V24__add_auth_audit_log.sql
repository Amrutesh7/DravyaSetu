-- Auth audit log for security events and compliance.
CREATE TABLE auth_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event VARCHAR(50) NOT NULL,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    email VARCHAR(255),
    ip VARCHAR(45),
    user_agent TEXT,
    success BOOLEAN NOT NULL,
    reason VARCHAR(100),
    metadata JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_auth_audit_user_created ON auth_audit_log (user_id, created_at DESC);
CREATE INDEX idx_auth_audit_event_created ON auth_audit_log (event, created_at DESC);
CREATE INDEX idx_auth_audit_email_created ON auth_audit_log (email, created_at DESC);
CREATE INDEX idx_auth_audit_ip_created ON auth_audit_log (ip, created_at DESC);